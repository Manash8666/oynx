export const getOnyxMotionTemplate = (idOrSlug: string): OnyxMotionTemplate | undefined => {
  const norm = idOrSlug.toLowerCase().trim()
  return ONYX_MOTION_TEMPLATES.find((t) => t.id === norm || t.slug === norm)
}

export const getOnyxMotionTemplatesByCategory = (category: string): readonly OnyxMotionTemplate[] => {
  if (!category || category === "all") return ONYX_MOTION_TEMPLATES
  return ONYX_MOTION_TEMPLATES.filter((t) => t.category === category || t.tags.includes(category))
}
