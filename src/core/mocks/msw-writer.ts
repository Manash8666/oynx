import { SchemaSynthesizer } from './schema-synthesizer.js';
import { FixtureGenerator } from './fixture-generator.js';
import type { RecordedNetworkCall, RouteFixture } from './types.js';

export class MswWriter {
  public static generateMswFileContent(calls: RecordedNetworkCall[]): string {
    const fixtureMap = new Map<string, RouteFixture>();

    for (const call of calls) {
      const urlObj = new URL(call.url, 'http://localhost');
      const { template, params } = SchemaSynthesizer.parameterizeRoute(urlObj.pathname);
      const key = `${call.method}:${template}`;

      if (!fixtureMap.has(key)) {
        fixtureMap.set(key, {
          routeTemplate: template,
          method: call.method,
          status: call.status,
          mockResponse: FixtureGenerator.sanitizePayload(call.responseBody),
          paramNames: params,
        });
      }
    }

    const lines: string[] = [
      '// Autogenerated by Onyx Deterministic Network & Mock Factory',
      "import { http, HttpResponse } from 'msw';",
      '',
      'export const handlers = [',
    ];

    for (const fixture of fixtureMap.values()) {
      const methodLower = fixture.method.toLowerCase();
      lines.push(`  http.${methodLower}('${fixture.routeTemplate}', () => {`);
      lines.push(`    return HttpResponse.json(`);
      lines.push(`      ${JSON.stringify(fixture.mockResponse, null, 6).trim()},`);
      lines.push(`      { status: ${fixture.status} }`);
      lines.push(`    );`);
      lines.push(`  }),`);
    }

    lines.push('];');
    lines.push('');

    return lines.join('\n');
  }
}
